// Only the native main process reads releases and writes installers. No renderer/IPC input.
const fs = require('node:fs/promises');
const path = require('node:path');
const { createHash } = require('node:crypto');
const RELEASES = 'https://api.github.com/repos/napo/qurioso/releases';
const RELEASE_PAGE = 'https://github.com/napo/qurioso/releases';
const MAX_INSTALLER_SIZE = 8 * 1024 ** 3;

function parseVersion(value) {
  const match = /^v?(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)(?:-([0-9A-Za-z.-]+))?(?:\+([0-9A-Za-z.-]+))?$/.exec(String(value));
  if (!match) return null;
  const numbers = match.slice(1, 4).map(Number);
  const pre = match[4]?.split('.') || [];
  if (!numbers.every(Number.isSafeInteger) || match[5]?.split('.').some(part => !part) || pre.some(part => !part || (/^\d+$/.test(part) && (part.length > 1 && part[0] === '0' || !Number.isSafeInteger(Number(part)))))) return null;
  return { numbers, pre };
}

function compareVersions(a, b) {
  const x = parseVersion(a), y = parseVersion(b);
  if (!x || !y) throw new Error('Numero di versione non valido.');
  for (let i = 0; i < 3; i++) if (x.numbers[i] !== y.numbers[i]) return x.numbers[i] > y.numbers[i] ? 1 : -1;
  if (!x.pre.length || !y.pre.length) return x.pre.length === y.pre.length ? 0 : x.pre.length ? -1 : 1;
  for (let i = 0; i < Math.max(x.pre.length, y.pre.length); i++) {
    if (x.pre[i] === undefined || y.pre[i] === undefined) return x.pre[i] === undefined ? -1 : 1;
    if (x.pre[i] === y.pre[i]) continue;
    const xn = /^\d+$/.test(x.pre[i]), yn = /^\d+$/.test(y.pre[i]);
    if (xn !== yn) return xn ? -1 : 1;
    return (xn ? Number(x.pre[i]) > Number(y.pre[i]) : x.pre[i] > y.pre[i]) ? 1 : -1;
  }
  return 0;
}

function selectRelease(releases, currentVersion) {
  const current = parseVersion(currentVersion);
  if (!current) throw new Error('Versione installata non valida.');
  return releases.filter(release => {
    const version = parseVersion(release?.tag_name);
    return version && !release.draft && (current.pre.length || (!release.prerelease && !version.pre.length)) && compareVersions(release.tag_name, currentVersion) > 0;
  }).sort((a, b) => compareVersions(b.tag_name, a.tag_name))[0] || null;
}

// Asset names are generated by electron-builder.yml; never guess a different CPU architecture.
function selectInstaller(release, platform, arch, linuxFormat = 'AppImage') {
  if (!['x64', 'arm64'].includes(arch) || !Array.isArray(release?.assets)) return null;
  const os = { win32: 'win', darwin: 'mac', linux: 'linux' }[platform];
  const ext = platform === 'win32' ? 'exe' : platform === 'darwin' ? 'dmg' : ['deb', 'rpm', 'AppImage'].includes(linuxFormat) ? linuxFormat : null;
  if (!os || !ext || !parseVersion(release.tag_name)) return null;
  const packageArch = platform === 'linux' ? (arch === 'x64' ? ext === 'deb' ? 'amd64' : 'x86_64' : ext === 'rpm' ? 'aarch64' : 'arm64') : arch;
  const names = [...new Set([arch, packageArch])].map(cpu => `Qurioso-${release.tag_name.replace(/^v/, '')}-${os}-${cpu}.${ext}`);
  return release.assets.find(asset => {
    if (!names.includes(asset?.name) || !Number.isSafeInteger(asset.size) || asset.size <= 0 || asset.size > MAX_INSTALLER_SIZE || !/^sha256:[a-f\d]{64}$/i.test(asset.digest || '')) return false;
    try {
      const url = new URL(asset.browser_download_url);
      return url.origin === 'https://github.com' && !url.username && !url.password && !url.search && !url.hash &&
        url.pathname === `/napo/qurioso/releases/download/${release.tag_name}/${asset.name}`;
    } catch { return false; }
  }) || null;
}

async function limitedJson(response) {
  let bytes = 0;
  const chunks = [];
  for await (const chunk of response.body) {
    bytes += chunk.length;
    if (bytes > 2 * 1024 ** 2) throw new Error('Risposta del server troppo grande.');
    chunks.push(Buffer.from(chunk));
  }
  return JSON.parse(Buffer.concat(chunks).toString('utf8'));
}

async function findUpdate(currentVersion, { fetchImpl = fetch, signal } = {}) {
  const beta = parseVersion(currentVersion)?.pre.length;
  const response = await fetchImpl(beta ? `${RELEASES}?per_page=100` : `${RELEASES}/latest`, {
    redirect: 'error', credentials: 'omit', signal: AbortSignal.any([AbortSignal.timeout(15000), ...(signal ? [signal] : [])]),
    headers: { Accept: 'application/vnd.github+json', 'User-Agent': 'Qurioso-update-check' },
  });
  if (response.status === 404) return null;
  if (!response.ok) throw new Error('GitHub non è raggiungibile o ha limitato le richieste.');
  const result = await limitedJson(response);
  return selectRelease(Array.isArray(result) ? result : [result], currentVersion);
}

function allowedDownloadUrl(value) {
  try {
    const url = new URL(value);
    return url.protocol === 'https:' && !url.username && !url.password && !url.port &&
      (url.hostname === 'github.com' && url.pathname.startsWith('/napo/qurioso/releases/download/') ||
       ['release-assets.githubusercontent.com', 'objects.githubusercontent.com'].includes(url.hostname));
  } catch { return false; }
}

async function downloadInstaller(asset, directory, { fetchImpl = fetch, signal, onProgress = () => {} } = {}) {
  // Revalidate even for callers other than the UI controller.
  if (!asset || !/^Qurioso-[\w.+-]+\.(exe|dmg|deb|rpm|AppImage)$/.test(asset.name) ||
      !Number.isSafeInteger(asset.size) || asset.size <= 0 || asset.size > MAX_INSTALLER_SIZE ||
      !/^sha256:[a-f\d]{64}$/i.test(asset.digest || '') || !allowedDownloadUrl(asset.browser_download_url) ||
      new URL(asset.browser_download_url).hostname !== 'github.com') throw new Error('Installer non verificabile.');
  await fs.mkdir(directory, { recursive: true, mode: 0o700 });
  const staging = await fs.mkdtemp(path.join(directory, 'download-'));
  const partial = path.join(staging, 'download.partial');
  let handle;
  try {
    const combinedSignal = AbortSignal.any([AbortSignal.timeout(30 * 60 * 1000), ...(signal ? [signal] : [])]);
    let url = asset.browser_download_url, response;
    for (let redirects = 0; redirects <= 5; redirects++) {
      if (!allowedDownloadUrl(url)) throw new Error('Destinazione del download non consentita.');
      response = await fetchImpl(url, { redirect: 'manual', credentials: 'omit', signal: combinedSignal, headers: { 'User-Agent': 'Qurioso-update-download' } });
      if (![301, 302, 303, 307, 308].includes(response.status)) break;
      const location = response.headers.get('location');
      await response.body?.cancel();
      if (!location || redirects === 5) throw new Error('Reindirizzamento del download non valido.');
      url = new URL(location, url).href;
    }
    if (!response?.ok || !response.body) throw new Error('Download non riuscito.');
    const declared = response.headers.get('content-length');
    if (declared !== null && Number(declared) !== asset.size) throw new Error('Dimensione del download inattesa.');
    handle = await fs.open(partial, 'wx', 0o600);
    const hash = createHash('sha256');
    let received = 0;
    for await (const chunk of response.body) {
      combinedSignal.throwIfAborted();
      received += chunk.length;
      if (received > asset.size) throw new Error('Dimensione del download inattesa.');
      hash.update(chunk);
      // FileHandle.write may perform a partial write.
      let offset = 0;
      while (offset < chunk.length) { const { bytesWritten } = await handle.write(chunk, offset, chunk.length - offset); if (!bytesWritten) throw new Error('Scrittura del download interrotta.'); offset += bytesWritten; }
      onProgress(received / asset.size);
    }
    combinedSignal.throwIfAborted();
    if (received !== asset.size || hash.digest('hex') !== asset.digest.slice(7).toLowerCase()) throw new Error('Verifica d’integrità del download non riuscita.');
    await handle.close(); handle = null;
    const file = path.join(staging, asset.name);
    await fs.rename(partial, file);
    if (file.endsWith('.AppImage')) await fs.chmod(file, 0o700);
    return file;
  } catch (error) {
    await handle?.close();
    await fs.rm(staging, { recursive: true, force: true });
    throw error;
  }
}

function detectLinuxFormat({ appImage = process.env.APPIMAGE, osRelease } = {}) {
  if (appImage) return 'AppImage';
  const family = String(osRelease || '').match(/^(?:ID|ID_LIKE)=(.*)$/gm)?.join(' ') || '';
  if (/debian|ubuntu|mint/i.test(family)) return 'deb';
  if (/fedora|rhel|centos|suse|rocky|almalinux/i.test(family)) return 'rpm';
  return 'AppImage';
}

async function readSettings(directory) {
  try { const data = JSON.parse(await fs.readFile(path.join(directory, 'update-settings.json'), 'utf8')); return { enabled: data.enabled !== false }; }
  catch { return { enabled: true }; }
}
async function writeSettings(directory, enabled) {
  await fs.mkdir(directory, { recursive: true });
  const file = path.join(directory, 'update-settings.json');
  await fs.writeFile(`${file}.tmp`, JSON.stringify({ enabled: Boolean(enabled) }), { mode: 0o600 });
  await fs.rename(`${file}.tmp`, file);
}

module.exports = { RELEASE_PAGE, parseVersion, compareVersions, selectRelease, selectInstaller, findUpdate, downloadInstaller, detectLinuxFormat, readSettings, writeSettings };
