const messages: Record<Language, Record<Key, string>> = { it, en, de };

/** Interface language set by LanguageProvider on <html lang>; English without a document or for other languages. */
export function serviceLanguage(): Language {
  const lang = typeof document === 'undefined' ? '' : document.documentElement.lang;
  return lang === 'it' || lang === 'de' ? lang : 'en';
}
export const serviceText = (key: Key) => messages[serviceLanguage()][key];
